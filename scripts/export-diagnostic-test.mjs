async function fetchTests() {
  // Query tests table for Diagnostic Test #1
  const url = `${BASE_URL}/tests?title=ilike.*Diagnostic Test #1*&select=*`;
  console.log('Fetching tests from:', url);
  const res = await fetch(url, { headers });
  if (!res.ok) {
    const text = await res.text();
    throw new Error(`HTTP ${res.status}: ${text}`);
  }
  return res.json();
}

async function fetchQuestions(testId) {
  const url = `${BASE_URL}/questions?test_id=eq.${testId}&select=*&order=order_index.asc`;
  console.log('Fetching questions for test:', testId);
  const res = await fetch(url, { headers });
  if (!res.ok) {
    const text = await res.text();
    throw new Error(`HTTP ${res.status}: ${text}`);
  }
  return res.json();
}

function generateTypeScript(test, questions) {
  const testData = {
    id: test.id,
    title: test.title,
    directions: test.directions || null,
    timeLimit: test.time_limit || test.timeLimit || 35,
    questions: questions.map((q) => ({
      id: q.id,
      type: q.type || 'multiple-choice',
      passage: q.passage || null,
      question: q.question || q.content || '',
      options: q.options || [],
      answers: q.answers || (q.answer ? [q.answer] : []),
    })),
  };

  return `// AUTO-GENERATED by scripts/export-diagnostic-test.mjs
// Do not edit manually — re-run the script to refresh

export interface TestQuestion {
  id: string;
  type: 'multiple-choice' | 'short-answer';
  passage?: string | null;
  question: string;
  options?: Array<{ id: string; text: string; type: 'correct' | 'distractor' }>;
  answers?: string[];
}

export interface DiagnosticTestData {
  id: string;
  title: string;
  directions?: string | null;
  timeLimit: number;
  questions: TestQuestion[];
}

const diagnosticTest1: DiagnosticTestData = ${JSON.stringify(testData, null, 2)};

export default diagnosticTest1;
`;
}

async function main() {
  try {
    console.log('Fetching Diagnostic Test #1 from sms Supabase...');
    const tests = await fetchTests();

    if (!tests || tests.length === 0) {
      console.log('No test found with title matching "Diagnostic Test #1"');
      console.log('Trying alternate query...');

      // Try without filter to see what tests exist
      const allRes = await fetch(`${BASE_URL}/tests?select=id,title&limit=20`, { headers });
      const allTests = await allRes.json();
      console.log('Available tests:', JSON.stringify(allTests, null, 2));
      process.exit(1);
    }

    const test = tests[0];
    console.log(`Found test: "${test.title}" (id: ${test.id})`);

    // Try to get questions — may be embedded in test or separate table
    let questions = [];
    if (test.questions && Array.isArray(test.questions)) {
      questions = test.questions;
      console.log(`Questions embedded in test: ${questions.length}`);
    } else {
      questions = await fetchQuestions(test.id);
      console.log(`Questions fetched separately: ${questions.length}`);
    }

    const ts = generateTypeScript(test, questions);

    const outDir = join(__dirname, '..', 'src', 'app', 'diagnosis', 'data');
    mkdirSync(outDir, { recursive: true });
    const outPath = join(outDir, 'diagnostic-test-1.ts');
    writeFileSync(outPath, ts);

    console.log(`\nSuccess! Written to: ${outPath}`);
    console.log(`Questions exported: ${questions.length}`);
  } catch (err) {
    console.error('Error:', err.message);
    process.exit(1);
  }
}

main();
